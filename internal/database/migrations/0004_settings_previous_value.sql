-- ============================================================
-- 0004_settings_previous_value —— 设置回滚所需的前值
-- ------------------------------------------------------------
-- 依据：docs/07-specs/f-9-01-system-settings.md（R-008 / Q-007）
--       docs/02-architecture/DATA_MODEL.md §2.1、§8
-- 变更要点：
--   previous_value：保存**最近一次变更前**的值，供「回滚」使用。
--
--   只保留最近一次而不建历史表（Q-007）：回滚是低频操作，而更早的历史
--   已经由审计流水承担——为回滚再引入一张无限增长的表，属于重复存储
--   同一份信息。
--
--   即时生效的设置项在应用失败时会自动回滚到该值（R-007），因此它是
--   回滚路径的必需字段，不是可选的便利字段。
--
-- 可重复执行：全部语句带 IF NOT EXISTS
-- ============================================================

ALTER TABLE system_setting ADD COLUMN IF NOT EXISTS previous_value text;
