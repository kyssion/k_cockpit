-- ============================================================
-- 0006 模型字段与表结构的列对齐
-- ------------------------------------------------------------
-- 背景：模型字段名到列名的转换由 GORM 的命名策略完成，而表由**手写 SQL 迁移**
-- 创建。两条路径各写一遍，不一致时：
--
--   - 不会编译报错；
--   - 不会被其它测试发现——测试库由 AutoMigrate 按**同一套策略**建表，
--     两边一起错，永远不会见面；
--   - 只在连上由迁移建的真实库时暴露，且表现为一个笼统的
--     「服务内部错误，请稍后重试」（执行器把写库失败统一收成了 500）。
--
-- 本项目确实踩过：`VCPU` 被转成 `v_cpu` 而库里是 `vcpu`，创建虚拟机必失败。
--
-- 本迁移补齐「模型声明了、表里没有」的列。
--
-- **命名策略导致的错误列名不用这里修**：迁移已应用，只增不改；那类问题在
-- 模型上显式声明 gorm:"column:xxx" 解决（已随本次一并修正 VCPU 与 CIDR）。
-- ============================================================

-- system_setting 缺 created_at（模型声明了 CreatedAt）。
--
-- 已有行统一填 now()：这不是它们真实的创建时间，但 system_setting 的
-- 语义是「当前值 + 上一次的值」，created_at 仅用于展示「这行记录何时出现」，
-- 用迁移时间近似比留空更有意义。若将来需要精确值，应以业务时间为准另记。
ALTER TABLE system_setting ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

-- storage_pool 缺 last_reported_at（模型声明了 LastReportedAt）。
--
-- 它是空间数据的最近上报时间，用于计算新鲜度（IsStale）。留空表示
-- 「从未上报」——这比填一个假的时间更诚实：填了假时间会让界面把一份从未
-- 同步过的数据当成刚刚同步过的。
ALTER TABLE storage_pool ADD COLUMN IF NOT EXISTS last_reported_at timestamptz;
