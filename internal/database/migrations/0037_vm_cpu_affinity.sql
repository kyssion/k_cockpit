-- 虚拟机的 CPU 亲和性（绑核），形如 "0-3" 或 "0,2,4"。
--
-- 与宿主机级「CPU 亲和性预设」（cpu_affinity_preset）的关系：预设是**可复用的候选**，"这台机器实际绑在哪几核"是**实例上的事实**，两者必须分开存——只存预设引用的话，改了预设会静默改动已建机器的绑定；只存字符串的话，用户每次都得手打 "0-3" 这种不直观的写法（预设给的是"绑前四核"这样的语义 + 描述）
--
-- 为空表示不绑核，由调度器自由迁移；非空时虚拟化层会限制 vCPU 只跑在指定核上。
ALTER TABLE vm ADD COLUMN IF NOT EXISTS cpu_affinity varchar(128);
