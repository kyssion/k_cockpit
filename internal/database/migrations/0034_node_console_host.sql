-- 节点的控制台对外地址。
--
-- 为什么需要它：控制台（SPICE / VNC）监听在**宿主机**上，而面板与浏览器
-- 之间的那条 WebSocket 是代理——代理能让人在网页里看到画面，却无法让
-- virt-viewer 这类本地客户端连上去。要生成 SPICE 连接文件（.vv），就必须
-- 知道"从用户的网络看过去，这台宿主机的控制台该连哪个地址"。
--
-- 为什么是**管理员填写**而不是自动探测：
--
--   - 节点在一个网段、用户在另一个网段时，宿主机自己知道的地址（内网 IP）
--     对用户不可达；
--   - 控制台可能监听在 127.0.0.1 上（默认更安全），此时对外可达的地址
--     是一个跳板或映射后的地址，只有部署者知道。
--
-- 留空表示"不提供连接文件"，而不是猜一个——猜错的连接文件会被当成
-- "下载了却连不上"，那比没有这个功能更让人困惑。
ALTER TABLE node ADD COLUMN IF NOT EXISTS console_host varchar(255);
