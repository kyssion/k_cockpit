-- "总共有多少"。只有两者都在，才能把"已承诺给虚拟机的 vCPU"换算成占比
-- ——工作台的「理论最大量」用的正是这个分母。
--
-- 在此之前核数只存在于**按需探测**的结果里（打开节点页时现取一次）。那
-- 意味着任何"按历史算承诺占比"的需求都只能回到逐节点探测：节点一多，
-- 打开一次工作台就变成一次对全部节点的探测风暴，而离线节点还会让数字
-- 缺一块。核数在一台机器的生命周期里几乎不变，随采样存一份是它该待的
-- 地方。

