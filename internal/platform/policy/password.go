// Package policy 收敛**跨入口**的安全策略常量。
//
// 存在的理由：同一个策略写在四个地方，就一定会分叉。密码下限曾同时是 8 与
// 12——管理员建号与自助改密按 8 位，而首次登录强制改密、找回密码重置、邀请
// 注册按 12 位。于是用户可以先按 12 位设一次，再在账号设置里把它降回 8 位，
// 而界面上没有任何地方说过规则变了。这属于「哪一处放松都会成为绕过其它几处
// 的路径」的典型。
package policy

// MinPasswordLength 是任何**人**设置的密码的最小长度。
//
// 口径统一覆盖：初始化管理员、管理员建号给的初始密码、首次登录强制改密、
// 自助改密、找回密码重置、邀请注册、应急脚本重置。
//
// 12 位而不是 8 位：这是既有实现里最严的一处（初始化管理员与找回密码重置），
// 而其它入口向它看齐，比把最严的一处放松要安全。密码哈希用 argon2id，
// 长度下限只挡「随手设一个」的情况。
const MinPasswordLength = 12
