package agent

// OpVMCDROMApply 下发光驱的期望状态（挂载 / 弹出 / 换盘 / 摘除 / 换总线）。
//
// 一个 Kind 覆盖五种动作是刻意的：对节点而言它们都是"把这台虚拟机的光驱
// 配置改成这个样子"——差别只在参数。拆成五个 Kind 会让节点侧把同一段
// 设备重建逻辑写五遍，而那是**最可能出分歧**的地方（某天给挂载那条加了
// 顺序校验，弹出那条没加）。
//
// 节点侧有两条要遵守：
//
//  1. **弹出是清空介质，不是移除设备**。来宾里应当仍然看得到一个空的托盘
//     （/dev/srN 还在）。把设备也摘掉的话，用户在来宾里找不到设备，而他会
//     以为是自己哪里配错了。
//  2. **换盘之后来宾不一定立刻看到新介质**。多数来宾会缓存介质信息，需要在
//     里面重新挂载（或重启）才认。这不是节点能解决的，但**节点必须如实
//     回报"已换，但来宾侧可能需要刷新"**——控制面据此提示用户，而不是让
//     他去猜"为什么换了的盘没生效"。
const OpVMCDROMApply OpKind = "vm.cdrom.apply"

// CDROMDataKey 是结果中承载补充信息的键。
const CDROMDataKey = "vm_cdrom"

// CDROMInfo 是下发结果。
type CDROMInfo struct {
	Message string
	// GuestRefreshNeeded 为 true 表示**来宾侧可能需要重新挂载或重启**。
	//
	// 必须显式告诉用户：多数学系统会缓存光驱里的介质信息，换了盘之后在
	// 来宾里看到的还是旧的那一张。不说的话，用户会以为换盘失败、反复重试。
	GuestRefreshNeeded bool
	// RebootNeeded 为 true 表示这次改动要重启虚拟机才生效。
	//
	// 换总线类型几乎一定需要（热插拔的总线支持各不相同）。与上一项分开：
	// 一个是"来宾里刷新一下"，另一个是"整台机器要重启"，代价差一个量级。
	RebootNeeded bool
}
